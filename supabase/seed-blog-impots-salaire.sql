<h2>7. Une nouveauté 2026 à ne pas manquer</h2>
<p>Au-delà des points de crédit, une mesure adoptée récemment prévoit, pour les olim et résidents de retour devenus résidents fiscaux entre le 5 novembre 2025 et le 31 décembre 2026, une <strong>exonération d'impôt sur les premiers revenus du travail générés en Israël</strong> pendant les deux premières années, dans la limite d'un plafond, avec un calcul au prorata si la résidence débute en cours d'année.</p>
<p>Le dispositif est neuf, technique, et s'ajoute aux avantages existants sans les remplacer. Si vous êtes concerné, c'est exactement le type de sujet où une heure chez un expert-comptable se rentabilise immédiatement.</p>

<h2>8. Le réflexe qui vous coûte cher si vous l'oubliez</h2>
<p>Vos points ne sont <strong>pas attribués automatiquement</strong>. Vous devez remplir le <strong>טופס 101</strong> (<em>tofes 101</em>) auprès de votre employeur — en début de contrat, puis <strong>chaque année en janvier</strong>. C'est ce formulaire qui déclare votre statut d'olé, vos enfants, votre situation familiale.</p>
<p>Beaucoup de nouveaux arrivants le remplissent à la va-vite, oublient de cocher leur statut d'olé, et paient plusieurs centaines de shekels de trop par mois pendant des années.</p>
<p>Bonne nouvelle si c'est votre cas : une demande de <strong>restitution d'impôt</strong> (<em>hehzer mas</em>) peut porter sur les <strong>six dernières années</strong>. Beaucoup d'olim récupèrent ainsi plusieurs milliers de shekels.</p>

