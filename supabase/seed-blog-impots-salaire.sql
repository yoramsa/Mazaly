<h2>4. Les nekudot zikuy : le cœur du système</h2>
<p>C'est ici que tout se joue, et c'est le point le plus mal compris par les nouveaux arrivants.</p>
<blockquote>Un point de crédit ne réduit pas votre revenu imposable : il se déduit directement de l'impôt à payer. C'est une réduction d'impôt, pas un abattement.</blockquote>
<p>En 2026, <strong>un point vaut 242 ₪ par mois</strong>, soit 2 904 ₪ par an. Cette valeur est gelée depuis 2025 et doit le rester jusqu'en 2027.</p>
<p>Le mécanisme est simple : on calcule l'impôt selon le barème, puis on soustrait la valeur totale de vos points. Si le résultat est négatif, vous ne payez pas d'impôt sur le revenu — mais l'excédent n'est ni remboursé ni reporté (sauf cas particuliers).</p>

