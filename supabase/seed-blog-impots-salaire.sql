<h2>5. Le bonus des olim : 42 mois d'avantage</h2>
<p>C'est l'un des avantages les plus concrets de l'alyah, et il est <strong>cumulatif</strong> avec les 2,25 points de résident. Le décompte court sur <strong>42 mois</strong> (3 ans et demi) à partir de la délivrance de votre Téoudat Olé — et non de votre première embauche.</p>
<p>Deux précisions qui comptent :</p>
<ul>
<li>Le compteur <strong>tourne même si vous ne travaillez pas</strong>. Un olé qui passe un an à l'oulpan avant de chercher un emploi consomme ses meilleurs mois d'avantage.</li>
<li>Il est en revanche <strong>suspendu</strong> pendant le service militaire ou des études supérieures, et reprend ensuite.</li>
</ul>

