<h2>1. Ce qui est prélevé sur votre salaire</h2>
<p>Trois prélèvements distincts sont retenus à la source par votre employeur :</p>
<ul>
<li><strong>מס הכנסה</strong> (<em>mas hakhnasa</em>) — l'impôt sur le revenu, progressif</li>
<li><strong>ביטוח לאומי</strong> (<em>Bituah Leumi</em>) — les cotisations de sécurité sociale</li>
<li><strong>מס בריאות</strong> (<em>mas briout</em>) — la cotisation santé, qui finance votre Kupat Holim</li>
</ul>
<p>Différence majeure avec la France : l'impôt sur le revenu est <strong>individuel</strong>. Pas de quotient familial, pas de foyer fiscal. Chaque salarié est imposé sur son propre revenu — et les charges de famille sont prises en compte autrement, précisément par les points de crédit.</p>

